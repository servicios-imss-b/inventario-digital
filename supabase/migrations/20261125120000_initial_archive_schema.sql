create table public.administrative_units (
  id bigint generated by default as identity primary key,
  owner_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  name text not null,
  created_at timestamptz not null default now(),
  unique (owner_id, id),
  unique (owner_id, name)
);

create table public.producing_areas (
  id bigint generated by default as identity primary key,
  owner_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  unit_id bigint,
  name text not null,
  created_at timestamptz not null default now(),
  unique (owner_id, id),
  unique (owner_id, unit_id, name),
  foreign key (owner_id, unit_id)
    references public.administrative_units (owner_id, id)
    on delete set null (unit_id)
);

create table public.cabinets (
  id bigint generated by default as identity primary key,
  owner_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  code text not null,
  name text not null,
  description text not null default '',
  columns_count integer not null default 2 check (columns_count > 0),
  rows_count integer not null default 3 check (rows_count > 0),
  material text not null default 'Madera',
  created_at timestamptz not null default now(),
  unique (owner_id, id),
  unique (owner_id, code)
);

create table public.sections (
  id bigint generated by default as identity primary key,
  owner_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  cabinet_id bigint not null,
  code text not null,
  name text not null,
  row_index integer not null,
  col_index integer not null,
  width_ratio integer not null default 50,
  notes text not null default '',
  unique (owner_id, id),
  unique (owner_id, cabinet_id, code),
  unique (owner_id, id, cabinet_id),
  foreign key (owner_id, cabinet_id)
    references public.cabinets (owner_id, id)
    on delete cascade
);

create table public.folders (
  id bigint generated by default as identity primary key,
  owner_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  uid text not null,
  consecutive_number text not null default '',
  administrative_unit_id bigint,
  administrative_unit_name text not null default '',
  producing_area_id bigint,
  producing_area_name text not null default '',
  expediente_name text not null,
  expediente_number text not null default '',
  documentary_year text not null default '',
  oldest_date text not null default '',
  newest_date text not null default '',
  folder_number text not null default '',
  observations text not null default '',
  spine_color text not null default 'blanco'
    check (spine_color in ('blanco', 'gris', 'azul', 'naranja', 'oscuro')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (owner_id, id),
  unique (owner_id, uid),
  foreign key (owner_id, administrative_unit_id)
    references public.administrative_units (owner_id, id)
    on delete set null (administrative_unit_id),
  foreign key (owner_id, producing_area_id)
    references public.producing_areas (owner_id, id)
    on delete set null (producing_area_id)
);

create table public.locations (
  id bigint generated by default as identity primary key,
  owner_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  folder_id bigint not null,
  cabinet_id bigint not null,
  section_id bigint not null,
  position_index integer not null default 1 check (position_index > 0),
  assigned_at timestamptz not null default now(),
  unique (owner_id, folder_id),
  foreign key (owner_id, folder_id)
    references public.folders (owner_id, id)
    on delete cascade,
  foreign key (owner_id, section_id, cabinet_id)
    references public.sections (owner_id, id, cabinet_id)
    on delete cascade
);

create table public.movement_history (
  id bigint generated by default as identity primary key,
  owner_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  folder_id bigint not null,
  folder_uid text not null,
  expediente_name text not null,
  previous_cabinet_name text,
  previous_section_name text,
  previous_position integer,
  new_cabinet_name text,
  new_section_name text,
  new_position integer,
  action_type text not null check (action_type in ('Asignación', 'Reubicación', 'Reordenamiento', 'Retiro')),
  notes text not null default '',
  moved_at timestamptz not null default now(),
  foreign key (owner_id, folder_id)
    references public.folders (owner_id, id)
    on delete cascade
);

create table public.archive_reports (
  id bigint generated by default as identity primary key,
  owner_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  administrative_unit_name text not null default '',
  producing_area_name text not null default '',
  report_date date,
  review_date date,
  checklist jsonb not null default '[]'::jsonb
    check (jsonb_typeof(checklist) = 'array' and jsonb_array_length(checklist) = 6),
  producer_oldest_year text not null default '',
  producer_newest_year text not null default '',
  coordinator_oldest_year text not null default '',
  coordinator_newest_year text not null default '',
  producer_signature text not null default '',
  coordinator_signature text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (owner_id, id)
);

create index producing_areas_owner_unit_idx on public.producing_areas (owner_id, unit_id);
create index sections_owner_cabinet_idx on public.sections (owner_id, cabinet_id);
create index folders_owner_area_idx on public.folders (owner_id, producing_area_id);
create index locations_owner_section_idx on public.locations (owner_id, section_id, position_index);
create index movement_history_owner_folder_idx on public.movement_history (owner_id, folder_id, moved_at desc);
create index archive_reports_owner_updated_idx on public.archive_reports (owner_id, updated_at desc);

do $$
declare
  table_name text;
begin
  foreach table_name in array array[
    'administrative_units',
    'producing_areas',
    'cabinets',
    'sections',
    'folders',
    'locations',
    'movement_history',
    'archive_reports'
  ] loop
    execute format('alter table public.%I enable row level security', table_name);
    execute format('revoke all on table public.%I from anon, authenticated', table_name);
    execute format(
      'grant select, insert, update, delete on table public.%I to authenticated',
      table_name
    );
    execute format(
      'create policy %I on public.%I for all to authenticated using ((select auth.uid()) = owner_id) with check ((select auth.uid()) = owner_id)',
      table_name || '_owner_access',
      table_name
    );
  end loop;
end;
$$;

